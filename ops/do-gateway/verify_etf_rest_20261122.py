    '    return {\n'
    '        "ticker": symbol, "exchange": exchange,\n'
    '        "rows": [rows_by_date[day] for day in sorted(rows_by_date)],\n'
    '        "source": "kiwoom:usa06012",\n'
    '    }\n'
