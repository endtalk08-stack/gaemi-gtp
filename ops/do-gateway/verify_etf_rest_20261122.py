def load_candidate(module_name, source):
    module = ModuleType(module_name)
    sys.modules[module_name] = module
    exec(compile(source, module_name, "exec"), module.__dict__)
    return module



def compact(row):
    keys = ("code", "stk_cd", "stex_tp", "etn", "mkgb", "isEtf")
    return {key: str(row[key])[:60] for key in keys if key in row}


def response_rows(data):
    rows = data.get("list")
    return [row for row in rows if isinstance(row, dict)] if isinstance(rows, list) else []


def matching_symbol(row, choices, re):
    code = str(row.get("code") or row.get("stk_cd") or "").strip().upper()
    parts = set(re.split(r"[^A-Z0-9]+", code))
    matches = choices & parts
    return next(iter(matches)) if len(matches) == 1 else None


def verify(provider, token):
    from collections import Counter
    import re

    choices = provider.ETF_TICKERS
    baseline = {}
    try:
        data = provider._call_once("usa10104", {"stex_tp": "%"}, token=token)
        rows = response_rows(data)
        counts = Counter(str(row.get("stex_tp", ""))[:20] for row in rows)
        tagged = [compact(row) for row in rows if matching_symbol(row, choices, re)]
        baseline = {
            "row_count": len(rows),
            "response_fields": sorted(data)[:20],
            "exchange_counts": dict(counts),
            "etn_counts": dict(Counter(str(row.get("etn", ""))[:20] for row in rows)),
            "has_next_page": data.get("_cont_yn") == "Y",
            "examples": [compact(row) for row in rows[:5]],
            "exact_ticker_examples": tagged[:28],
        }
    except provider.KiwoomReadOnlyError as exc:
        baseline = {"error": str(exc)}

    provider.API_PATHS["usa10098"] = "/api/us/stkinfo"
    looked_up = {}
    mappings = {}
    for ticker in sorted(choices):
        try:
            data = provider._call_once("usa10098", {"stk_cd": ticker}, token=token)
        except provider.KiwoomReadOnlyError as exc:
            looked_up[ticker] = {"error": str(exc)}
            continue
        rows = response_rows(data)
        matched = [row for row in rows if matching_symbol(row, {ticker}, re)]
        looked_up[ticker] = {"row_count": len(rows), "rows": [compact(row) for row in (matched or rows)[:4]]}
        exchanges = {str(row.get("stex_tp", "")).strip().upper() for row in matched}
        exchanges = {provider.EXCHANGE_CODES.get(code, code) for code in exchanges}
        valid = exchanges & provider.EXCHANGES
        if len(valid) == 1:
            mappings[ticker] = next(iter(valid))

    return {
        "source": {"list": "kiwoom:usa10104", "lookup": "kiwoom:usa10098"},
        "raw_first_list_page": baseline,
        "ticker_lookup": looked_up,
        "verified_exchanges": mappings,
        "unresolved_tickers": sorted(choices - mappings.keys()),
    }


def probe_etf_websocket(token, exchanges):
    """Read-only LOGIN + FE registration for the fourteen verified ETFs."""
    import asyncio

    expected = {
        "XLK", "XLV", "XLF", "XLY", "XLC", "XLI", "XLP",
        "XLE", "XLU", "XLRE", "XLB", "SOXX", "XBI", "IBIT",
    }
    if set(exchanges) != expected:
        return {"error": "etf_exchange_map_incomplete", "mapped_count": len(exchanges)}

    async def run():
        try:
            from websockets.asyncio.client import connect
        except ImportError:
            from websockets.client import connect

        result = {
            "mapped_count": len(exchanges),
            "login_ack": False,
            "registration_ack": False,
            "registered_tickers": sorted(exchanges),
            "real_frames": 0,
            "fe_events": 0,
            "tick_symbols": {},
        }
        async with connect(
            "wss://api.kiwoom.com:10000/api/us/websocket",
            open_timeout=8, close_timeout=2, ping_interval=None, max_size=131072,
        ) as ws:
            await ws.send(json.dumps({"trnm": "LOGIN", "token": token}))
            loop = asyncio.get_running_loop()
            deadline = loop.time() + 12
            while loop.time() < deadline:
                try:
                    raw = await asyncio.wait_for(ws.recv(), timeout=min(3, deadline-loop.time()))
                except asyncio.TimeoutError:
                    continue
                if isinstance(raw, bytes):
                    raw = raw.decode("utf-8", errors="replace")
                try:
                    frame = json.loads(raw)
                except (TypeError, ValueError):
                    continue
                if not isinstance(frame, dict):
                    continue
                trnm = str(frame.get("trnm") or "").upper()
                if trnm == "PING":
                    await ws.send(json.dumps(frame))
                elif trnm == "LOGIN":
                    result["login_ack"] = str(frame.get("return_code", "")) in ("0", "0000")
                    break

            if not result["login_ack"]:
                result["result"] = "login_not_confirmed"
                return result

            items = [
                {"jmcode": symbol, "stex_tp": exchange}
                for symbol, exchange in sorted(exchanges.items())
            ]
            await ws.send(json.dumps({
                "trnm": "REG", "grp_no": "1", "refresh": "1",
                "data": [{"item": items, "type": ["FE"]}],
            }))
            deadline = loop.time() + 15
            while loop.time() < deadline and not result["registration_ack"]:
                try:
                    raw = await asyncio.wait_for(ws.recv(), timeout=min(3, deadline-loop.time()))
                except asyncio.TimeoutError:
                    continue
                if isinstance(raw, bytes):
                    raw = raw.decode("utf-8", errors="replace")
                try:
                    frame = json.loads(raw)
                except (TypeError, ValueError):
                    continue
                if not isinstance(frame, dict):
                    continue
                trnm = str(frame.get("trnm") or "").upper()
                if trnm == "PING":
                    await ws.send(json.dumps(frame))
                elif trnm == "REG":
                    result["registration_ack"] = str(frame.get("return_code", "")) in ("0", "0000")
                elif trnm == "REAL":
                    result["real_frames"] += 1
                    rows = frame.get("data")
                    if not isinstance(rows, list):
                        continue
                    for row in rows[:50]:
                        if not isinstance(row, dict) or str(row.get("type") or "").upper() != "FE":
                            continue
                        result["fe_events"] += 1
                        raw_symbol = str(row.get("item") or "").strip().upper()
                        symbol = raw_symbol
                        for separator in (".", ":"):
                            if separator in symbol:
                                parts = symbol.split(separator)
                                symbol = parts[0] if parts[0] in exchanges else parts[-1]
                                break
                        if symbol not in exchanges:
                            continue
                        values = row.get("values")
                        if not isinstance(values, dict):
                            continue
                        def number(value):
                            try:
                                parsed = float(str(value).strip().replace(",", ""))
                                return parsed if -1e12 < parsed < 1e12 else None
                            except (TypeError, ValueError):
                                return None
                        result["tick_symbols"][symbol] = {
                            "price": abs(number(values.get("10"))) if number(values.get("10")) not in (None, 0) else None,
                            "change_pct": number(values.get("12")),
                        }

            if not result["registration_ack"]:
                result["result"] = "registration_not_confirmed"
            else:
                result["result"] = "live_ticks_received" if result["tick_symbols"] else "registered_no_tick_in_window"
        return result

    try:
        return asyncio.run(run())
    except Exception as exc:
        return {"error_type": type(exc).__name__, "result": "websocket_probe_error"}


def main():
    quotes = load_candidate("backend.providers.kiwoom_us_quotes", QUOTES_SOURCE)
    provider = load_candidate("backend.providers.kiwoom_us_industries", INDUSTRIES_SOURCE)
